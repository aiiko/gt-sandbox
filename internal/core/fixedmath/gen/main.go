// gen genera sintable.go: el seno del primer cuadrante en punto fijo.
// Se ejecuta una sola vez (go generate) y la tabla se commitea, para que la
// simulación nunca dependa de math.Sin en runtime (podría variar por
// plataforma, p. ej. con FMA).
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"math"
	"os"
)

const (
	quarter = 1024    // pasos por cuarto de vuelta
	one     = 1 << 30 // 1.0 en punto fijo
)

func main() {
	var b bytes.Buffer
	b.WriteString("// Code generated by gen/main.go; DO NOT EDIT.\n\npackage fixedmath\n\n")
	fmt.Fprintf(&b, "// sinTable[i] = round(sin(i/%d · π/2) · 2^30), i en [0, %d].\n", quarter, quarter)
	fmt.Fprintf(&b, "var sinTable = [%d]int32{\n", quarter+1)
	for i := 0; i <= quarter; i++ {
		v := int64(math.Round(math.Sin(float64(i)/quarter*math.Pi/2) * one))
		fmt.Fprintf(&b, "%d,", v)
		if i%8 == 7 {
			b.WriteByte('\n')
		}
	}
	b.WriteString("\n}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("sintable.go", src, 0o644); err != nil {
		panic(err)
	}
}
